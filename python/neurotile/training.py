"""NumPy-only training, training-set calibration, exact integer export."""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

import numpy as np

from .dataset import ROOT, load_dataset
from .model import predict, validate_model


def _forward(x, params):
    w1, b1, w2, b2 = params
    hidden = np.maximum(0.0, x @ w1 + b1)
    return hidden, hidden @ w2 + b2


def _quantized_batch(x, model):
    """Int64 work arrays avoid host overflow; exported values fit int32."""
    w1 = np.asarray(model["w1"], dtype=np.int64).reshape(64, 32)
    w2 = np.asarray(model["w2"], dtype=np.int64).reshape(32, 10)
    hidden = np.clip((x @ w1 + model["b1"]) >> model["hidden_shift"], 0, 127)
    logits = hidden @ w2 + model["b2"]
    return hidden, logits


def _header(model):
    lines = [
        "/* Generated by tools/train_model.py; do not edit by hand. */",
        "/* Dataset: Alpaydin & Kaynak, UCI Optical Digits, CC BY 4.0. */",
        "#ifndef NEUROTILE_GENERATED_MODEL_H", "#define NEUROTILE_GENERATED_MODEL_H",
        "#include <stdint.h>", "#define NT_INPUTS 64", "#define NT_HIDDEN 32",
        "#define NT_OUTPUTS 10", f"#define NT_HIDDEN_SHIFT {model['hidden_shift']}",
    ]
    for ctype, name, values in (
        ("int8_t", "nt_w1", model["w1"]), ("int32_t", "nt_b1", model["b1"]),
        ("int8_t", "nt_w2", model["w2"]), ("int32_t", "nt_b2", model["b2"]),
        ("int8_t", "nt_sample_input", model["sample_input"]),
    ):
        lines.append(f"static const {ctype} {name}[{len(values)}] = {{")
        for offset in range(0, len(values), 16):
            lines.append("    " + ", ".join(str(v) for v in values[offset:offset + 16]) + ",")
        lines.append("};")
    lines += [f"static const int nt_sample_label = {model['sample_label']};", "#endif", ""]
    return "\n".join(lines)


def train_and_export(output_root: Path = ROOT, seed: int = 2026, epochs: int = 180) -> dict:
    """Train with a fixed schedule; inspect official test data only at the end.

    The 180-epoch schedule is fixed, without test-based early stopping or
    hyperparameter search. Inputs divide by the known physical bound 16; no
    statistics are fitted to test data. Quantization scales use only weights
    and training activations. The official split separates writers.
    """
    train_rows, train_labels = load_dataset("train")
    test_rows, test_labels = load_dataset("test")
    x_int = np.asarray(train_rows, dtype=np.int64)
    x = x_int.astype(np.float64) / 16.0
    y = np.asarray(train_labels, dtype=np.int64)
    rng = np.random.default_rng(seed)
    params = [rng.normal(0, np.sqrt(2 / 64), (64, 32)), np.zeros(32),
              rng.normal(0, np.sqrt(1 / 32), (32, 10)), np.zeros(10)]
    moments = [np.zeros_like(p) for p in params]
    velocities = [np.zeros_like(p) for p in params]
    batch_size, rate, decay = 128, 0.003, 0.0001
    step = 0
    for epoch in range(epochs):
        order = rng.permutation(len(x))
        losses = []
        for start in range(0, len(order), batch_size):
            indices = order[start:start + batch_size]
            xb, yb = x[indices], y[indices]
            hidden, logits = _forward(xb, params)
            logits -= logits.max(axis=1, keepdims=True)
            probabilities = np.exp(logits)
            probabilities /= probabilities.sum(axis=1, keepdims=True)
            losses.append(float(-np.log(np.maximum(probabilities[np.arange(len(indices)), yb], 1e-12)).mean()))
            gradient = probabilities.copy()
            gradient[np.arange(len(indices)), yb] -= 1
            gradient /= len(indices)
            grad_w2 = hidden.T @ gradient + decay * params[2]
            grad_b2 = gradient.sum(axis=0)
            grad_hidden = (gradient @ params[2].T) * (hidden > 0)
            gradients = [xb.T @ grad_hidden + decay * params[0], grad_hidden.sum(axis=0),
                         grad_w2, grad_b2]
            step += 1
            for p, m, v, g in zip(params, moments, velocities, gradients):
                m *= 0.9
                m += 0.1 * g
                v *= 0.999
                v += 0.001 * g * g
                p -= rate * (m / (1 - 0.9**step)) / (np.sqrt(v / (1 - 0.999**step)) + 1e-8)
        if epoch == 0 or (epoch + 1) % 30 == 0 or epoch + 1 == epochs:
            print(f"epoch {epoch + 1:3d}/{epochs}: training loss {np.mean(losses):.6f}", flush=True)

    w1, b1, w2, b2 = params
    scale1 = 127 / float(np.max(np.abs(w1)))
    qw1 = np.clip(np.rint(w1 * scale1), -127, 127).astype(np.int64)
    qb1 = np.rint(b1 * 16 * scale1).astype(np.int64)
    train_accumulators = x_int @ qw1 + qb1
    calibration_peak = int(np.maximum(train_accumulators, 0).max())
    hidden_shift = max(0, math.ceil(math.log2(max(1, calibration_peak) / 127)))
    hidden_scale = 16 * scale1 / (2**hidden_shift)
    scale2 = 127 / float(np.max(np.abs(w2)))
    qw2 = np.clip(np.rint(w2 * scale2), -127, 127).astype(np.int64)
    qb2 = np.rint(b2 * hidden_scale * scale2).astype(np.int64)
    model = {
        "format": "neurotile-q8-v1", "input_size": 64, "hidden_size": 32, "output_size": 10,
        "matrix_layout": "flat row-major input x output", "hidden_shift": hidden_shift,
        "w1": qw1.ravel().tolist(), "b1": qb1.tolist(),
        "w2": qw2.ravel().tolist(), "b2": qb2.tolist(),
        "sample_input": test_rows[0], "sample_label": test_labels[0],
        "sample_test_index": 0,
        "quantization": {
            "input_range": [0, 16], "weight_range": [-127, 127],
            "hidden_range": [0, 127], "round_weights": "nearest ties to even",
            "hidden_rounding": "floor arithmetic right shift, then saturate 0..127",
            "scale1": scale1, "scale2": scale2, "hidden_float_scale": hidden_scale,
            "calibration": "maximum quantized hidden accumulator over training samples only",
            "training_calibration_peak": calibration_peak,
        },
        "training": {
            "algorithm": "64->32 ReLU ->10 softmax, minibatch Adam; NumPy only",
            "epochs": epochs, "batch_size": batch_size, "learning_rate": rate,
            "l2_weight_decay": decay, "seed": seed, "numpy_version": np.__version__,
            "split": "official UCI writer-disjoint train/test; no test tuning or early stopping",
        },
        "dataset": {
            "name": "UCI Optical Recognition of Handwritten Digits",
            "authors": "E. Alpaydin and C. Kaynak (1998)",
            "doi": "https://doi.org/10.24432/C50P49", "license": "CC BY 4.0",
            "provenance_file": "data/provenance.json",
        },
    }
    validate_model(model)
    # This is the sole test evaluation; quantization did not inspect test values.
    test_x = np.asarray(test_rows, dtype=np.int64)
    test_y = np.asarray(test_labels, dtype=np.int64)
    _, float_logits = _forward(test_x.astype(np.float64) / 16, params)
    _, integer_logits = _quantized_batch(test_x, model)
    _, train_logits = _quantized_batch(x_int, model)
    predictions = integer_logits.argmax(axis=1)
    confusion = np.zeros((10, 10), dtype=np.int64)
    np.add.at(confusion, (test_y, predictions), 1)
    metrics = {
        "float_test_accuracy": float(np.mean(float_logits.argmax(axis=1) == test_y)),
        "quantized_test_accuracy": float(np.mean(predictions == test_y)),
        "quantized_train_accuracy": float(np.mean(train_logits.argmax(axis=1) == y)),
        "correct_test_predictions": int(np.sum(predictions == test_y)),
        "train_samples": len(x), "test_samples": len(test_y), "split_seed": None,
        "training_seed": seed, "confusion_matrix": confusion.tolist(),
        "confusion_matrix_axes": "rows true labels 0..9; columns predicted labels 0..9",
        "macs_per_inference": 2368, "weights_and_biases_bytes": 2536,
    }
    model["metrics"] = metrics
    model["sample_reference"] = predict(model["sample_input"], model)
    for sample_index in (0, 1, 31, len(test_y) - 1):
        reference = predict(test_rows[sample_index], model)
        if reference["logits"] != integer_logits[sample_index].tolist():
            raise RuntimeError("Scalar reference and vectorized integer evaluation disagree")
    output_root = Path(output_root)
    (output_root / "models").mkdir(parents=True, exist_ok=True)
    (output_root / "firmware" / "generated").mkdir(parents=True, exist_ok=True)
    payload = json.dumps(model, indent=2) + "\n"
    model_path = output_root / "models" / "digits_q8.json"
    model_path.write_text(payload, encoding="utf-8", newline="\n")
    (output_root / "models" / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8", newline="\n")
    (output_root / "models" / "digits_q8.sha256").write_text(hashlib.sha256(payload.encode()).hexdigest() + "  digits_q8.json\n", encoding="ascii", newline="\n")
    (output_root / "firmware" / "generated" / "model.h").write_text(_header(model), encoding="ascii", newline="\n")
    print(json.dumps(metrics, indent=2), flush=True)
    print(f"Exported {model_path}", flush=True)
    return model
