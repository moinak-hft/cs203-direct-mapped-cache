"""Fixed-schedule NumPy-only genuine MNIST trainer and INT8/C exporter."""
from __future__ import annotations
import hashlib
import json
import math
from pathlib import Path
import numpy as np
from .hd_dataset import ROOT,load_hd_dataset
from .hd_model import validate_hd_model,predict_hd


def _forward(x,params):
    w1,b1,w2,b2=params
    hidden=np.maximum(0,x@w1+b1)
    return hidden,hidden@w2+b2


def _quantized_batch(x,model):
    w1=np.asarray(model['w1'],dtype=np.int32).reshape(784,64)
    w2=np.asarray(model['w2'],dtype=np.int32).reshape(64,10)
    hidden=np.clip((x@w1+np.asarray(model['b1'],dtype=np.int32))>>model['hidden_shift'],0,127)
    return hidden,hidden@w2+np.asarray(model['b2'],dtype=np.int32)


def _header(model):
    lines=['/* Generated by tools/train_hd_model.py; genuine MNIST, attributed in data/mnist_README.md. */',
           '#ifndef NEUROTILE_MNIST_MODEL_H','#define NEUROTILE_MNIST_MODEL_H','#include <stdint.h>',
           '#define HD_INPUTS 784','#define HD_HIDDEN 64','#define HD_OUTPUTS 10',
           f'#define HD_HIDDEN_SHIFT {model["hidden_shift"]}']
    for ctype,name,values in [('int8_t','hd_w1',model['w1']),('int32_t','hd_b1',model['b1']),
                              ('int8_t','hd_w2',model['w2']),('int32_t','hd_b2',model['b2']),
                              ('int8_t','hd_sample_input',model['sample_input'])]:
        lines.append(f'static const {ctype} {name}[{len(values)}] = {{')
        for offset in range(0,len(values),16):lines.append('    '+', '.join(map(str,values[offset:offset+16]))+',')
        lines.append('};')
    lines.extend([f'static const int hd_sample_label = {model["sample_label"]};','#endif',''])
    return '\n'.join(lines)


def train_hd_and_export(output_root:Path=ROOT,seed:int=2026,epochs:int=40)->dict:
    """Train a fixed40epoch schedule; official10k test evaluated once at end.

    There is no test-based checkpoint, early stopping or hyperparameter search.
    Quantizer scales/calibration use trained weights and training data only.
    """
    rows,labels=load_hd_dataset('train')
    x_int=np.asarray([list(row)for row in rows],dtype=np.int32)
    x=x_int.astype(np.float32)/16
    y=np.asarray(labels,dtype=np.int64)
    rng=np.random.default_rng(seed)
    params=[rng.normal(0,np.sqrt(2/784),(784,64)).astype(np.float32),np.zeros(64,dtype=np.float32),
            rng.normal(0,np.sqrt(1/64),(64,10)).astype(np.float32),np.zeros(10,dtype=np.float32)]
    moments=[np.zeros_like(p)for p in params];velocities=[np.zeros_like(p)for p in params]
    step=0;batch_size=128;learning_rate=.0015;decay=.0001
    for epoch in range(epochs):
        order=rng.permutation(len(x));losses=[]
        for start in range(0,len(x),batch_size):
            indices=order[start:start+batch_size];xb=x[indices];yb=y[indices]
            hidden,logits=_forward(xb,params);logits-=logits.max(axis=1,keepdims=True)
            probabilities=np.exp(logits);probabilities/=probabilities.sum(axis=1,keepdims=True)
            losses.append(float(-np.log(np.maximum(probabilities[np.arange(len(indices)),yb],1e-12)).mean()))
            gradient=probabilities.copy();gradient[np.arange(len(indices)),yb]-=1;gradient/=len(indices)
            grad_w2=hidden.T@gradient+decay*params[2];grad_b2=gradient.sum(axis=0)
            grad_hidden=(gradient@params[2].T)*(hidden>0)
            gradients=[xb.T@grad_hidden+decay*params[0],grad_hidden.sum(axis=0),grad_w2,grad_b2]
            step+=1
            for p,m,v,g in zip(params,moments,velocities,gradients):
                m*=.9;m+=.1*g;v*=.999;v+=.001*g*g
                p-=learning_rate*(m/(1-.9**step))/(np.sqrt(v/(1-.999**step))+1e-8)
        if epoch==0 or (epoch+1)%10==0 or epoch==epochs-1:
            print(f'HD epoch {epoch+1}/{epochs}: training loss {np.mean(losses):.6f}',flush=True)
    w1,b1,w2,b2=params
    scale1=127/float(np.abs(w1).max());qw1=np.rint(w1*scale1).clip(-127,127).astype(np.int32)
    qb1=np.rint(b1*16*scale1).astype(np.int32)
    # Chunk calibration bounds memory and uses training pixels only.
    peak=0
    for start in range(0,len(x_int),512):peak=max(peak,int((x_int[start:start+512]@qw1+qb1).max()))
    hidden_shift=max(0,math.ceil(math.log2(max(1,peak)/127)))
    hidden_scale=16*scale1/(2**hidden_shift)
    scale2=127/float(np.abs(w2).max());qw2=np.rint(w2*scale2).clip(-127,127).astype(np.int32)
    qb2=np.rint(b2*hidden_scale*scale2).astype(np.int32)
    test_rows,test_labels=load_hd_dataset('test')
    model={'format':'neurotile-mnist-q8-v1','input_size':784,'hidden_size':64,'output_size':10,
           'image_width':28,'image_height':28,'matrix_layout':'flat row-major input x output',
           'hidden_shift':hidden_shift,'w1':qw1.ravel().tolist(),'b1':qb1.tolist(),
           'w2':qw2.ravel().tolist(),'b2':qb2.tolist(),'sample_input':list(test_rows[0]),
           'sample_label':test_labels[0],'sample_test_index':0,
           'training':{'algorithm':'784->64ReLU->10softmax; minibatch Adam; NumPy-only',
                       'seed':seed,'epochs':epochs,'batch_size':batch_size,'learning_rate':learning_rate,
                       'l2_weight_decay':decay,'numpy_version':np.__version__,
                       'schedule':'Fixed before test evaluation; no early stopping/test tuning',
                       'subset':'2000perclass from official train only; original test untouched'},
           'quantization':{'input_range':[0,16],'input_transform':'(uint8*16+127)//255',
                           'hidden_range':[0,127],'weight_range':[-127,127],
                           'hidden_rounding':'floor arithmetic shift then clip0..127',
                           'scale1':scale1,'scale2':scale2,'training_calibration_peak':peak,
                           'calibration':'maximum hidden accumulator on training subset only'},
           'dataset':{'name':'MNIST','authors':'Yann LeCun, Corinna Cortes, Christopher J. C. Burges',
                      'source':'https://ossci-datasets.s3.amazonaws.com/mnist/',
                      'license':'MIT per ylecun/mnist dataset card',
                      'provenance_file':'data/mnist_provenance.json'}}
    validate_hd_model(model)
    test_x=np.asarray([list(row)for row in test_rows],dtype=np.int32);test_y=np.asarray(test_labels)
    _,float_logits=_forward(test_x.astype(np.float32)/16,params)
    predicted=[];logit_chunks=[]
    for start in range(0,len(test_x),512):
        _,logits=_quantized_batch(test_x[start:start+512],model)
        predicted.extend(logits.argmax(axis=1).tolist());logit_chunks.append(logits)
    predictions=np.asarray(predicted);integer_logits=np.concatenate(logit_chunks)
    confusion=np.zeros((10,10),dtype=np.int32);np.add.at(confusion,(test_y,predictions),1)
    metrics={'float_test_accuracy':float(np.mean(float_logits.argmax(axis=1)==test_y)),
             'quantized_test_accuracy':float(np.mean(predictions==test_y)),
             'correct_test_predictions':int(np.sum(predictions==test_y)),
             'train_samples':len(x),'official_train_samples':60000,'test_samples':len(test_y),
             'training_seed':seed,'confusion_matrix':confusion.tolist(),
             'confusion_matrix_axes':'rows true label0..9; columns predicted0..9',
             'macs_per_inference':50816,'weights_and_biases_bytes':51112,
             'evaluation':'All10000 official test samples; no synthetic pair accuracy claim'}
    model['metrics']=metrics;model['sample_reference']=predict_hd(model['sample_input'],model)
    for index in [0,1,31,9999]:
        if predict_hd(list(test_rows[index]),model)['logits']!=integer_logits[index].tolist():
            raise RuntimeError('Scalar/vectored HD integer inference disagree')
    examples=[]
    for digit in range(10):
        # First by position, irrespective of prediction; no cherry-picking.
        index=test_labels.index(digit)
        examples.append({'index':index,'label':digit,'pixels':list(test_rows[index])})
    output_root=Path(output_root);(output_root/'models').mkdir(parents=True,exist_ok=True)
    (output_root/'firmware/generated').mkdir(parents=True,exist_ok=True)
    payload=json.dumps(model,separators=(',',':'))+'\n'
    (output_root/'models/mnist_q8.json').write_text(payload,encoding='utf-8',newline='\n')
    (output_root/'models/mnist_metrics.json').write_text(json.dumps(metrics,indent=2)+'\n',encoding='utf-8',newline='\n')
    (output_root/'models/mnist_q8.sha256').write_text(hashlib.sha256(payload.encode()).hexdigest()+'  mnist_q8.json\n',encoding='ascii',newline='\n')
    (output_root/'models/mnist_examples.json').write_text(json.dumps(examples,separators=(',',':'))+'\n',encoding='utf-8',newline='\n')
    (output_root/'firmware/generated/mnist_model.h').write_text(_header(model),encoding='ascii',newline='\n')
    print(json.dumps(metrics,indent=2),flush=True)
    return model
